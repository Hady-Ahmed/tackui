def test_platform_models_endpoint(client, monkeypatch):
    # The seeded catalog lists both models; tier flags default to False.
    res = client.get("/platform/models", headers=admin_headers(sub="frontend-service"))
    assert res.status_code == 200
    body = res.json()["models"]
    tiered = {m["id"]: m["platform_tier"] for m in body}
    assert set(tiered) == {"gpt-4o-mini", "z-ai/glm-5.3-flash"}
    assert tiered["gpt-4o-mini"] is False and tiered["z-ai/glm-5.3-flash"] is False
    # requires_key rides along (keyless providers like ollama would carry
    # false; every provider constructible here takes an api key).
    assert all(m["requires_key"] is True for m in body)

    # Re-enable with a tier flag via the admin API — the revision bump is
    # picked up live, no restart.
    res = client.put(
        "/platform/catalog/models",
        headers=admin_headers(sub="frontend-service"),
        json={
            "providers": [
                {"slug": "openai-chat", "enabled": True, "models": ["gpt-4o-mini:tier"]},
                {"slug": "openrouter", "enabled": True, "models": ["z-ai/glm-5.3-flash"]},
            ]
        },
    )
    assert res.status_code == 200, res.text
    res = client.get("/platform/models", headers=admin_headers(sub="frontend-service"))
    tiered = {m["id"]: m["platform_tier"] for m in res.json()["models"]}
    assert tiered["gpt-4o-mini"] is True

    # Platform key missing → the model is STILL LISTED (registry membership
    # is key-independent — a runner's own key signs BYOK runs) but it can no
    # longer be platform-tier: tier means "the platform key pays for this".
    monkeypatch.delenv("OPENAI_API_KEY", raising=False)
    res = client.get("/platform/models", headers=admin_headers(sub="frontend-service"))
    body = res.json()
    assert [m["id"] for m in body["models"]] == ["gpt-4o-mini", "z-ai/glm-5.3-flash"]
    assert body["models"][0]["platform_tier"] is False

    # Service-only surface: user tokens are rejected (GET /* admin catch-all).
    assert client.get("/platform/models", headers=user_headers()).status_code == 403


