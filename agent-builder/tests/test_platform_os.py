def test_validation_errors_never_echo_submitted_values(client):
    """FastAPI/pydantic 4xx bodies echo the *submitted value* back in each
    error's ``input`` field by default. The client forwards this service's 4xx
    detail to the browser (client-fixable errors pass through), so a secret
    submitted in a bad-typed field would reflect into the client-visible
    error. The sanitized handler keeps only loc/msg/type — the error stays
    readable without echoing the payload."""
    marker = "sk-secret-in-bad-field"
    payload = component_payload()
    # Wrong TYPE on purpose: a dict where `stage: str` is expected — the
    # pydantic 422 path. (A bad *value* like a marker string instead of
    # draft/published is caught by agno's own 400 check, which echoes the
    # value in its detail string — see the note below.)
    payload["stage"] = {"secret": marker}
    res = client.post("/components", headers=admin_headers(sub="frontend-service"), json=payload)
    assert res.status_code == 422, res.text
    assert marker not in res.text
    # Field location and message survive — the error is still actionable.
    first = res.json()["detail"][0]
    assert first["loc"] and first["msg"]


