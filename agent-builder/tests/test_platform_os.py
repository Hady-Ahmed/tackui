# MCP connector per-run token delivery (the v1 go/no-go)
# ---------------------------------------------------------------------------


class _TokenGate:
    """ASGI wrapper rejecting requests without the expected bearer token."""

    def __init__(self, app, token: str):
        self.app = app
        self.token = token.encode()

    async def __call__(self, scope, receive, send):
        if scope["type"] == "http":
            headers = dict(scope.get("headers", []))
            if headers.get(b"authorization") != b"Bearer " + self.token:
                await send(
                    {
                        "type": "http.response.start",
                        "status": 401,
                        "headers": [(b"content-type", b"text/plain")],
                    }
                )
                await send({"type": "http.response.body", "body": b"unauthorized"})
                return
        await self.app(scope, receive, send)


@pytest.mark.asyncio
async def test_mcp_connector_per_run_token():
    """Prove (or kill) per-run MCP token delivery: MCPTools connects with
    per-instance headers against a live streamable-http server."""
    import uvicorn
    from fastmcp import FastMCP

    mcp = FastMCP("test-mcp")

    @mcp.tool
    def echo(text: str) -> str:
        return f"echo:{text}"

    socket_first = socket.socket()
    socket_first.bind(("127.0.0.1", 0))
    port = socket_first.getsockname()[1]
    socket_first.close()

    config = uvicorn.Config(
        _TokenGate(mcp.http_app(path="/mcp"), "test-mcp-token"),
        host="127.0.0.1",
        port=port,
        log_level="error",
    )
    server = uvicorn.Server(config)
    thread = threading.Thread(target=server.run, daemon=True)
    thread.start()
    try:
        for _ in range(50):
            if server.started:
                break
            import asyncio

            await asyncio.sleep(0.1)
        assert server.started, "uvicorn did not start"

        from agno.tools.mcp import MCPTools

        # Correct per-run token -> connects and lists the tool.
        # (The session exists only inside the async context — __aenter__ is
        # what performs the handshake; a bare initialize() is a silent no-op.)
        async with MCPTools(
            url=f"http://127.0.0.1:{port}/mcp",
            transport="streamable-http",
            headers={"Authorization": "Bearer test-mcp-token"},
        ) as mcp_tools:
            names = list(mcp_tools.functions.keys()) if hasattr(mcp_tools, "functions") else []
            assert "echo" in names

        # Wrong token -> the handshake must fail (auth enforced at connect).
        with pytest.raises(Exception):
            async with MCPTools(
                url=f"http://127.0.0.1:{port}/mcp",
                transport="streamable-http",
                headers={"Authorization": "Bearer wrong-token"},
            ):
                pass  # pragma: no cover — must not be reached
    finally:
        server.should_exit = True
        thread.join(timeout=5)
