PlatformOpenAIChat = platform_model_class(OpenAIChat, "openai_api_key", "OPENAI_API_KEY")


class RecordingModel(PlatformOpenAIChat):
    """Records the API key each client construction resolved, then aborts the run.

    The MagicMock client records create() call args even though side_effect
    raises — so both the resolved key AND the outbound messages are captured.
    """

    calls = []

    def get_async_client(self):
        # Mirror the real fallback chain: instance key, then the env key
        # (OpenAIChat resolves the env key inside _get_client_params, so an
        # un-run instance still reports api_key=None).
        import os

        key = self._per_run_api_key() or self.api_key or os.getenv("OPENAI_API_KEY")
        stub = MagicMock()
        stub.chat.completions.create.side_effect = RuntimeError("recorded — abort run")
        RecordingModel.calls.append({"key": key, "client": stub})
        return stub


