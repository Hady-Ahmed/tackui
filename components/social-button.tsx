const PROVIDER_ICONS: Record<SocialProvider, ReactNode> = {
  google: <GoogleIcon />,
  github: <GitHubIcon />,
  oidc: <SsoIcon />,
};

/**
 * Social sign-in button with provider icon.
 *
 * Shared between the login and signup pages. Renders an inline SVG icon
 * (Google multi-color G, GitHub mark, or a generic key icon for OIDC SSO)
 * to the left of the label text.
 *
 * Google's icon is always full-color (standard pattern — the colored G is
 * recognizable in both light and dark mode). GitHub and SSO icons use
 * `currentColor` so they adapt to the theme automatically.
 */
export function SocialButton({
  provider,
  label,
  onClick,
}: {
  provider: SocialProvider;
  label: string;
  onClick: () => void;
}) {
  return (
    <button
      onClick={onClick}
      className="flex w-full items-center justify-center gap-2.5 rounded-lg border border-zinc-200 px-4 py-2 text-sm font-medium text-zinc-700 transition-colors hover:bg-zinc-100 dark:border-zinc-700 dark:text-zinc-300 dark:hover:bg-zinc-800"
    >
      {PROVIDER_ICONS[provider]}
      {label}
    </button>
  );
}
